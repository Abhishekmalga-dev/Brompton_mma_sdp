** Description     : DDL for the 5 wrapup_summary final tables.
**                   CONVERSATION (header) : INQUIRY (1-to-many, FK
**                   CONVERSATION_ID) : INQUIRY_INTENT /
**                   INQUIRY_KEY_POINT / INQUIRY_TOPIC (many-to-one,
**                   FK INQUIRY_ID). Tables are dropped child-to-parent
**                   and created parent-to-child so each FK always has
**                   a valid parent to reference at create time.
**                   NOTE: Snowflake PK/FK constraints are declarative
**                   only and are not enforced at runtime.
