USE SCHEMA ADMIN;

--==========================================================================
--Step 1: Drop existing final tables (child-to-parent order)
--==========================================================================

CALL TOOLS.ADMIN.SP_DROP_OBJECT('TABLE', 'ADMIN.ASDT_WRAPUP_SUMMARY_INQUIRY_TOPIC');
CALL TOOLS.ADMIN.SP_DROP_OBJECT('TABLE', 'ADMIN.ASDT_WRAPUP_SUMMARY_INQUIRY_KEY_POINT');
CALL TOOLS.ADMIN.SP_DROP_OBJECT('TABLE', 'ADMIN.ASDT_WRAPUP_SUMMARY_INQUIRY_INTENT');
CALL TOOLS.ADMIN.SP_DROP_OBJECT('TABLE', 'ADMIN.ASDT_WRAPUP_SUMMARY_INQUIRY');
CALL TOOLS.ADMIN.SP_DROP_OBJECT('TABLE', 'ADMIN.ASDT_WRAPUP_SUMMARY_CONVERSATION');

--==========================================================================
--Step 2: Create ASDT_WRAPUP_SUMMARY_CONVERSATION (header, grain: 1 row per conversation)
--==========================================================================

CREATE TABLE ASDT_WRAPUP_SUMMARY_CONVERSATION (
    CONVERSATION_ID VARCHAR(100) NOT NULL,
    MESSAGE_ID VARCHAR(100),
    SEQUENCE_NUMBER NUMBER,
    GENERATED_AT TIMESTAMP_NTZ,
    MODEL_VERSION VARCHAR(100),
    PROMPT_TOKENS NUMBER,
    COMPLETION_TOKENS NUMBER,
    TOTAL_TOKENS NUMBER,
    UPDATED_ON TIMESTAMP_NTZ NOT NULL,
    LOAD_TS TIMESTAMP_NTZ NOT NULL,
    CONSTRAINT ASDT_WRAPUP_SUMMARY_CONVERSATION_PK PRIMARY KEY (CONVERSATION_ID)
);

CALL TOOLS.ADMIN.SP_APPLY_GRANT('GRANT REFERENCES, SELECT ON ASDT_WRAPUP_SUMMARY_CONVERSATION TO ROLE XXX_RESTRICTED_TABLEREADER');
CALL TOOLS.ADMIN.SP_APPLY_GRANT('GRANT REFERENCES, INSERT, UPDATE, DELETE, TRUNCATE ON ASDT_WRAPUP_SUMMARY_CONVERSATION TO ROLE XXX_TABLEWRITER');
CALL TOOLS.ADMIN.SP_APPLY_GRANT('GRANT OWNERSHIP ON TABLE ASDT_WRAPUP_SUMMARY_CONVERSATION TO ROLE XXX_OWNER COPY CURRENT GRANTS');

--==========================================================================
--Step 3: Create ASDT_WRAPUP_SUMMARY_INQUIRY (grain: 1 row per inquiry, FK to CONVERSATION)
--==========================================================================

CREATE TABLE ASDT_WRAPUP_SUMMARY_INQUIRY (
    INQUIRY_ID VARCHAR(32) NOT NULL,
    CONVERSATION_ID VARCHAR(100) NOT NULL,
    INQUIRY_NUMBER VARCHAR(100),
    INQUIRY_ROLE VARCHAR(50),
    INQUIRY_PARENT_NUMBER VARCHAR(100),
    CLASSIFICATION VARCHAR(200),
    DESCRIPTION VARCHAR(4000),
    RESOLUTION VARCHAR(4000),
    STATUS VARCHAR(50),
    INQUIRY_SUMMARY VARCHAR(4000),
    MEME_CK VARCHAR(100),
    UPDATED_ON TIMESTAMP_NTZ NOT NULL,
    LOAD_TS TIMESTAMP_NTZ NOT NULL,
    CONSTRAINT ASDT_WRAPUP_SUMMARY_INQUIRY_PK PRIMARY KEY (INQUIRY_ID),
    CONSTRAINT ASDT_WRAPUP_SUMMARY_INQUIRY_FK1 FOREIGN KEY (CONVERSATION_ID)
        REFERENCES ASDT_WRAPUP_SUMMARY_CONVERSATION (CONVERSATION_ID)
);

CALL TOOLS.ADMIN.SP_APPLY_GRANT('GRANT REFERENCES, SELECT ON ASDT_WRAPUP_SUMMARY_INQUIRY TO ROLE XXX_RESTRICTED_TABLEREADER');
