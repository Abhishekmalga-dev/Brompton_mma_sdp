--==========================================================================
--Step 4: Create ASDT_WRAPUP_SUMMARY_INQUIRY_INTENT (grain: 1 row per intent, FK to INQUIRY)
--==========================================================================

CREATE TABLE ASDT_WRAPUP_SUMMARY_INQUIRY_INTENT (
