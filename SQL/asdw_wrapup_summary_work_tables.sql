** Description     : DDL for the 5 wrapup_summary work (staging) tables.
**                   CONVERSATION (header) : INQUIRY (1-to-many) :
**                   INQUIRY_INTENT / INQUIRY_KEY_POINT / INQUIRY_TOPIC
**                   (many-to-one back to INQUIRY via INQUIRY_ID).
**                   Tables are dropped child-to-parent and created
**                   parent-to-child since work tables carry the same
