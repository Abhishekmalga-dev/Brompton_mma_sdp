USE SCHEMA ADMIN;

--==========================================================================
--Step 1: Drop existing work tables (child-to-parent order)
--==========================================================================

CALL TOOLS.ADMIN.SP_DROP_OBJECT('TABLE', 'ADMIN.ASDW_WRAPUP_SUMMARY_INQUIRY_TOPIC_LOAD');
CALL TOOLS.ADMIN.SP_DROP_OBJECT('TABLE', 'ADMIN.ASDW_WRAPUP_SUMMARY_INQUIRY_KEY_POINT_LOAD');
