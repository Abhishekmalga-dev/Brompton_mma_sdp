--==========================================================================
--Step 2: Create ASDW_WRAPUP_SUMMARY_CONVERSATION_LOAD (header, grain: 1 row per conversation)
--==========================================================================

CREATE TABLE ASDW_WRAPUP_SUMMARY_CONVERSATION_LOAD (
    CONVERSATION_ID VARCHAR(100) NOT NULL,
    MESSAGE_ID VARCHAR(100),
    SEQUENCE_NUMBER NUMBER,
    GENERATED_AT TIMESTAMP_NTZ,
    MODEL_VERSION VARCHAR(100),
    PROMPT_TOKENS NUMBER,
    COMPLETION_TOKENS NUMBER,
    TOTAL_TOKENS NUMBER,
    UPDATED_ON TIMESTAMP_NTZ NOT NULL,
    LOAD_TS TIMESTAMP_NTZ NOT NULL
);

CALL TOOLS.ADMIN.SP_APPLY_GRANT('GRANT REFERENCES, SELECT ON ASDW_WRAPUP_SUMMARY_CONVERSATION_LOAD TO ROLE XXX_RESTRICTED_TABLEREADER');
